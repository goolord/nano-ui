def codepoint_allowed(cp):
    return cp in DISCRETE_CODEPOINTS or any(a <= cp <= b for a, b in RANGES)


def main():
    font = TTFont("cozette.otb")

    for tag in ("DSIG", "gasp", "hdmx", "LTSH", "VDMX", "vmtx", "vhea", "PCLT",
                "prep", "fpgm", "cvt ", "BDF ", "FFTM", "MATH", "GDEF", "glyf", "loca"):
        if tag in font:
            del font[tag]

    if "head" in font:
        font["head"].created = font["head"].modified = 3400000000

    if "post" in font:
        font["post"].formatType, font["post"].extraNames = 3.0, []

    if "name" in font:
        names = [r for r in font["name"].names if r.nameID == 1 and r.platformID == 3][:1]
        if names:
            names[0].string = "C".encode("utf-16-be")
        font["name"].names = names

    if "OS/2" in font:
        font["OS/2"].achVendID = b"    "

    kept = {".notdef"}
    if "cmap" in font:
        cmap = font["cmap"]
        ucs4 = [t for t in cmap.tables if t.platformID == 3 and t.platEncID == 10]
        cmap.tables = [ucs4[0]] if ucs4 else cmap.tables[:1]
        for t in cmap.tables:
            t.cmap = {cp: name for cp, name in t.cmap.items() if codepoint_allowed(cp)}
            kept.update(t.cmap.values())

    order = [g for g in font.getGlyphOrder() if g in kept]
    if ".notdef" not in order:
        order.insert(0, ".notdef")

    if "EBLC" in font and "EBDT" in font:
        strike_glyphs = font["EBDT"].strikeData[0]
        bitmap_glyphs = [g for g in order if g in strike_glyphs]
        order = bitmap_glyphs + [g for g in order if g not in strike_glyphs]

        sub = font["EBLC"].strikes[0].indexSubTables[0]
        sub.names, sub.firstGlyphIndex = bitmap_glyphs, 0
        sub.lastGlyphIndex = len(bitmap_glyphs) - 1
        font["EBLC"].strikes[0].indexSubTables = [sub]

        font["EBDT"].strikeData = [
            {g: d for g, d in s.items() if g in strike_glyphs and g in kept}
            for s in font["EBDT"].strikeData
        ]

    font.setGlyphOrder(order)
    if "maxp" in font:
        font["maxp"].numGlyphs = len(order)

    new_hmtx = newTable("hmtx")
    new_hmtx.metrics = {g: (6, 0) for g in order}
    font["hmtx"] = new_hmtx
    if "hhea" in font:
        font["hhea"].numberOfHMetrics = 1

    font.save("cozette.min.otb")
    print(f"Generated cozette.min.otb ({len(order)} glyphs)")


if __name__ == "__main__":
    main()
